// ─────────────────────────────────────────────────────────────
// PrimeEdge Marketing Film V2 — 30-second conversion cut
// 1920×1080 · 30fps · 900 frames
// Brand film → Product proof film
// ─────────────────────────────────────────────────────────────
import React, { useEffect } from "react";
import {
  AbsoluteFill,
  Audio,
  Sequence,
  staticFile,
  delayRender,
  continueRender,
  useVideoConfig,
} from "remotion";
import { COLORS } from "../../utils/colors";
import { loadGoogleFonts } from "../../utils/fonts";
import { V2_SCENES, V2_TOTAL_FRAMES } from "./timing";
import { S1_Hook }       from "./scenes/S1_Hook";
import { S2_Pain }       from "./scenes/S2_Pain";
import { S3_Introduce }  from "./scenes/S3_Introduce";
import { S4_DemoTakeIt } from "./scenes/S4_DemoTakeIt";
import { S5_DemoWait }   from "./scenes/S5_DemoWait";
import { S6_Journal }    from "./scenes/S6_Journal";
import { S7_CTA }        from "./scenes/S7_CTA";

export type MarketingV2Data = Record<string, never>;
export const defaultMarketingV2Props: MarketingV2Data = {};

const useFonts = () => {
  useEffect(() => {
    const handle = delayRender("Fonts");
    loadGoogleFonts().then(() => continueRender(handle));
  }, []);
};

// ── Audio availability helper ─────────────────────────────────
const hasAudio = (id: string): boolean => {
  // In production these are generated by generate_vo_v2.py
  // For dev without audio, set REMOTION_NO_AUDIO=1
  return process.env.REMOTION_NO_AUDIO !== "1";
};

export const MarketingV2: React.FC<MarketingV2Data> = () => {
  useFonts();
  const { fps } = useVideoConfig();

  const sc = V2_SCENES;

  return (
    <AbsoluteFill style={{ background: COLORS.bg, fontFamily: "Inter, SF Pro Display, sans-serif" }}>

      {/* ── Music bed (reuse existing ambient from V1 if present) ── */}
      {hasAudio("bed") && (
        <Audio
          src={staticFile("audio/bed.wav")}
          volume={(f) => {
            // Fade in over 30 frames, fade out over last 30 frames
            if (f < 30) return f / 30 * 0.18;
            if (f > V2_TOTAL_FRAMES - 30) return ((V2_TOTAL_FRAMES - f) / 30) * 0.18;
            return 0.18;
          }}
        />
      )}

      {/* ── Scene 1: Hook (0–60) ── */}
      <Sequence from={sc.hook.from} durationInFrames={sc.hook.frames}>
        {hasAudio("hook_v2") && <Audio src={staticFile("audio/hook_v2.mp3")} />}
        <S1_Hook />
      </Sequence>

      {/* ── Scene 2: Pain (60–180) ── */}
      <Sequence from={sc.pain.from} durationInFrames={sc.pain.frames}>
        {hasAudio("pain_v2") && <Audio src={staticFile("audio/pain_v2.mp3")} />}
        <S2_Pain />
      </Sequence>

      {/* ── Scene 3: Introduce PrimeEdge (180–270) ── */}
      <Sequence from={sc.introduce.from} durationInFrames={sc.introduce.frames}>
        {hasAudio("introduce_v2") && <Audio src={staticFile("audio/introduce_v2.mp3")} />}
        <S3_Introduce />
      </Sequence>

      {/* ── Scene 4: Demo — TAKE IT (270–510) ── */}
      <Sequence from={sc.demoTake.from} durationInFrames={sc.demoTake.frames}>
        {hasAudio("demo_take_v2") && <Audio src={staticFile("audio/demo_take_v2.mp3")} />}
        <S4_DemoTakeIt />
      </Sequence>

      {/* ── Scene 5: Demo — WAIT (510–660) ── */}
      <Sequence from={sc.demoWait.from} durationInFrames={sc.demoWait.frames}>
        {hasAudio("demo_wait_v2") && <Audio src={staticFile("audio/demo_wait_v2.mp3")} />}
        <S5_DemoWait />
      </Sequence>

      {/* ── Scene 6: Journal (660–780) ── */}
      <Sequence from={sc.journal.from} durationInFrames={sc.journal.frames}>
        {hasAudio("journal_v2") && <Audio src={staticFile("audio/journal_v2.mp3")} />}
        <S6_Journal />
      </Sequence>

      {/* ── Scene 7: CTA (780–900) ── */}
      <Sequence from={sc.cta.from} durationInFrames={sc.cta.frames}>
        {hasAudio("cta_v2") && <Audio src={staticFile("audio/cta_v2.mp3")} />}
        <S7_CTA />
      </Sequence>

    </AbsoluteFill>
  );
};
